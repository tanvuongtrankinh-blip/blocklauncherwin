#!/usr/bin/env python3
"""Generate ModPE constant tables (ChatColor, EntityType, ...) from the original Java sources."""
import re, sys, json, pathlib
src = pathlib.Path(sys.argv[1])  # .../src/net/zhuoweizhang/mcpelauncher
out = pathlib.Path(sys.argv[2])
files = {
 "ChatColor": src/"ChatColor.java", "ItemCategory": src/"ItemCategory.java",
 "BlockFace": src/"api/modpe/BlockFace.java", "DimensionId": src/"api/modpe/DimensionId.java",
 "EntityType": src/"api/modpe/EntityType.java", "ParticleType": src/"api/modpe/ParticleType.java",
 "Enchantment": src/"api/modpe/Enchantment.java", "BlockRenderLayer": src/"api/modpe/BlockRenderLayer.java",
 "EntityRenderType": src/"api/modpe/EntityRenderType.java", "ArmorType": src/"api/modpe/ArmorType.java",
 "MobEffect": src/"api/modpe/MobEffect.java", "UseAnimation": src/"api/modpe/UseAnimation.java",
}
res = {}
for name, f in files.items():
    t = re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", f.read_text(encoding="utf-8"), flags=re.S))
    d = {}
    for m in re.finditer(r"\b(?:int\s+)?([A-Za-z][A-Za-z0-9_]*)\s*=\s*([^,;]+)", t):
        k, v = m.group(1), m.group(2).strip()
        if k in ("BEGIN",) or k.startswith("effectIds"): continue
        s = re.fullmatch(r'BEGIN\s*\+\s*"(.*)"', v)
        if s: d[k] = "§" + s.group(1)
        elif re.fullmatch(r"-?(0x[0-9a-fA-F]+|\d+)", v): d[k] = int(v, 0)
        elif re.fullmatch(r'"(.*)"', v): d[k] = v[1:-1]
    res[name] = d
res["MobEffect"] = dict(movementSpeed=1,movementSlowdown=2,digSpeed=3,digSlowdown=4,damageBoost=5,heal=6,harm=7,jump=8,confusion=9,regeneration=10,damageResistance=11,fireResistance=12,waterBreathing=13,invisibility=14,blindness=15,nightVision=16,hunger=17,weakness=18,poison=19,wither=20,healthBoost=21,absorption=22,saturation=23,levitation=24,fatalPoison=25)
lines = ["// <auto-generated> by tools/gen_constants.py from the original BlockLauncher sources."]
for n, d in res.items():
    lines.append(f"var {n} = {json.dumps(d, ensure_ascii=False)};")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print({n: len(d) for n, d in res.items()})
